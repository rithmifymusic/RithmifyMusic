// Kill switch: early mobile builds cached the app shell here, which served stale files after updates.
// Browsers re-fetch this file, so installed copies replace themselves with this one, clear all caches and unregister.
self.addEventListener('install', () => self.skipWaiting());

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.map((key) => caches.delete(key)));
    await self.registration.unregister();
    const clients = await self.clients.matchAll({ type: 'window' });
    for (const client of clients) client.navigate(client.url);
  })());
});
